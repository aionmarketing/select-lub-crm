/**
 * Turns `ownership.json` into the two artifacts that make table ownership real:
 *
 * - `db/grants.generated.sql` — one `module_<name>` Postgres role per module,
 *   granted `INSERT, UPDATE, DELETE` on the tables it owns and `SELECT` on the
 *   tables whose owner lists it in `readableBy`. `db:migrate` applies it after
 *   `prisma migrate deploy`, so every database the repository migrates has the
 *   roles.
 * - `packages/core/src/kernel/db.modules.generated.ts` — `ModuleName` and
 *   `Owned`, so `db.tx(module, …)` takes a module name the compiler knows and a
 *   slice's queries can be checked against the tables its module owns.
 *
 * Neither file is edited by hand. `--check` regenerates both in memory and
 * diffs them against what is on disk, exiting non-zero and naming the stale
 * file; `packages/core/test/grants.test.ts` is that check, and it is what stops
 * `ownership.json` and the grants drifting apart.
 *
 * Usage:
 *   tsx scripts/gen-grants.ts            # write both files
 *   tsx scripts/gen-grants.ts --check    # fail if either is out of date
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";

/** One module's entry in `ownership.json`. */
export interface OwnershipModule {
  description?: string;
  tables: string[];
  /** `"*"` means every module may read these tables; an array names them. */
  readableBy: "*" | string[];
}

/** The parsed `ownership.json`. */
export interface Ownership {
  modules: Record<string, OwnershipModule>;
  /** Tables owned ahead of the migration that creates them, keyed by table name. */
  pendingTables?: Record<string, string>;
}

/** The repository root, from this file's location. */
const ROOT = resolve(import.meta.dirname, "..");

const SQL_PATH = resolve(ROOT, "db/grants.generated.sql");
const TS_PATH = resolve(ROOT, "packages/core/src/kernel/db.modules.generated.ts");

/**
 * The Postgres role name for a module.
 *
 * Module names are kebab-case (`plate-lookup`); role names are snake_case, so
 * they need no quoting in a `SET LOCAL ROLE` and read the same in `pg_roles`.
 */
export function roleFor(module: string): string {
  return `module_${module.replace(/-/g, "_")}`;
}

/** Reads and parses `ownership.json` from the repository root. */
export function readOwnership(root: string = ROOT): Ownership {
  return JSON.parse(readFileSync(resolve(root, "ownership.json"), "utf8")) as Ownership;
}

/** Module names in a stable order, so regenerating never produces a spurious diff. */
function moduleNames(ownership: Ownership): string[] {
  return Object.keys(ownership.modules).sort();
}

/**
 * The modules allowed to read a given owner's tables.
 *
 * `"*"` expands to every module including the owner itself; an explicit list is
 * taken as written, with the owner added — a module always reads what it owns.
 */
function readersOf(ownership: Ownership, owner: string): string[] {
  const entry = ownership.modules[owner];
  if (!entry) throw new Error(`unknown module: ${owner}`);
  const readers =
    entry.readableBy === "*" ? moduleNames(ownership) : [...entry.readableBy];
  if (!readers.includes(owner)) readers.push(owner);
  return [...new Set(readers)].sort();
}

/**
 * Renders `db/grants.generated.sql`.
 *
 * Three properties the SQL has to have, and why:
 *
 * - **Idempotent.** `db:migrate` reapplies it on every run, including against a
 *   database that already has the roles, so every statement either creates
 *   something absent or restates something present.
 * - **Membership granted to `current_user`.** Per-worktree databases are owned
 *   by whichever role `DATABASE_URL` names, and `SET ROLE` is refused unless
 *   the login role is a member of the target. The grant is `EXECUTE format(…)`
 *   over `current_user` rather than a hard-coded name so one generated file
 *   works for every checkout.
 * - **Tolerant of a table that does not exist yet.** `erp_outbox` is owned by
 *   `erp` from wave 1 but is not created until wave 3A's migration. A plain
 *   `GRANT` on a missing table aborts the script, so every grant is guarded by
 *   `to_regclass`. The guard is not a silent skip: `schema-ownership.test.ts`
 *   is what fails when a table is missing for any other reason.
 */
export function renderGrantsSql(ownership: Ownership): string {
  const modules = moduleNames(ownership);
  const roles = modules.map(roleFor);
  const out: string[] = [];

  out.push("-- Generated by scripts/gen-grants.ts from ownership.json. Do not edit.");
  out.push(
    "-- Regenerate with `pnpm gen:grants`; `packages/core/test/grants.test.ts` fails if this file is stale.",
  );
  out.push("--");
  out.push(
    "-- One role per module. A module may write only the tables it owns and read only",
  );
  out.push(
    "-- the tables whose owner lists it in `readableBy`. The kernel's `db.tx(module, fn)`",
  );
  out.push(
    "-- runs `SET LOCAL ROLE` before the callback, so a foreign write is refused by the",
  );
  out.push("-- database rather than by review.");
  out.push("");

  out.push(
    "-- Create every module role if absent, and make the login role a member of each so",
  );
  out.push(
    "-- `SET ROLE` is permitted. `current_user` rather than a literal: each worktree",
  );
  out.push("-- database is owned by whatever role its DATABASE_URL names.");
  out.push("DO $$");
  out.push("DECLARE");
  out.push("  target text;");
  out.push("BEGIN");
  out.push(
    `  FOREACH target IN ARRAY ARRAY[${roles.map((r) => `'${r}'`).join(", ")}] LOOP`,
  );
  out.push("    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = target) THEN");
  out.push("      EXECUTE format('CREATE ROLE %I NOLOGIN', target);");
  out.push("    END IF;");
  out.push("    EXECUTE format('GRANT USAGE ON SCHEMA public TO %I', target);");
  out.push("    EXECUTE format('GRANT %I TO %I', target, current_user);");
  out.push("  END LOOP;");
  out.push("END $$;");
  out.push("");

  out.push(
    "-- Start from nothing on every run, so a table removed from a module's list loses",
  );
  out.push(
    "-- the grant it used to have instead of keeping it until someone drops the role.",
  );
  out.push("DO $$");
  out.push("DECLARE");
  out.push("  target text;");
  out.push("BEGIN");
  out.push(
    `  FOREACH target IN ARRAY ARRAY[${roles.map((r) => `'${r}'`).join(", ")}] LOOP`,
  );
  out.push(
    "    EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA public FROM %I', target);",
  );
  out.push("  END LOOP;");
  out.push("END $$;");
  out.push("");

  for (const module of modules) {
    const role = roleFor(module);
    const owned = [...ownership.modules[module]!.tables].sort();
    out.push(`-- ${module} -> ${role}`);
    out.push(
      `-- owns ${owned.length} table(s); readable by: ${readersOf(ownership, module).join(", ")}`,
    );
    out.push("DO $$");
    out.push("DECLARE");
    out.push("  target text;");
    out.push("BEGIN");
    for (const table of owned) {
      const readers = readersOf(ownership, module).map(roleFor);
      out.push(`  IF to_regclass('public.${table}') IS NOT NULL THEN`);
      out.push(
        `    EXECUTE format('GRANT INSERT, UPDATE, DELETE ON public.${table} TO %I', '${role}');`,
      );
      out.push(
        `    FOREACH target IN ARRAY ARRAY[${readers.map((r) => `'${r}'`).join(", ")}] LOOP`,
      );
      out.push(
        `      EXECUTE format('GRANT SELECT ON public.${table} TO %I', target);`,
      );
      out.push("    END LOOP;");
      out.push("  END IF;");
    }
    out.push("END $$;");
    out.push("");
  }

  return out.join("\n");
}

/** Renders `packages/core/src/kernel/db.modules.generated.ts`. */
export function renderModulesTs(ownership: Ownership): string {
  const modules = moduleNames(ownership);
  const lines: string[] = [];

  lines.push("/**");
  lines.push(" * Generated by scripts/gen-grants.ts from ownership.json. Do not edit.");
  lines.push(" *");
  lines.push(
    " * Regenerate with `pnpm gen:grants`. `packages/core/test/grants.test.ts` fails",
  );
  lines.push(
    " * when this file and `ownership.json` disagree, so the type a slice is checked",
  );
  lines.push(" * against and the grants the database enforces cannot drift apart.");
  lines.push(" */");
  lines.push("");
  lines.push("/** Every module that owns tables. `db.tx` takes one of these. */");
  lines.push(
    `export const MODULE_NAMES = [${modules.map((m) => `"${m}"`).join(", ")}] as const;`,
  );
  lines.push("");
  lines.push("/** The name of a module, as written in ownership.json. */");
  lines.push("export type ModuleName = (typeof MODULE_NAMES)[number];");
  lines.push("");
  lines.push("/**");
  lines.push(" * The tables each module owns, and so the only tables it may write.");
  lines.push(" *");
  lines.push(" * These are table names (the Prisma `@@map` value), not model names.");
  lines.push(" */");
  lines.push("export const OWNED = {");
  for (const module of modules) {
    const owned = [...ownership.modules[module]!.tables].sort();
    lines.push(`  "${module}": [${owned.map((t) => `"${t}"`).join(", ")}],`);
  }
  lines.push("} as const satisfies Record<ModuleName, readonly string[]>;");
  lines.push("");
  lines.push("/** The tables owned by one module. */");
  lines.push("export type Owned<M extends ModuleName> = (typeof OWNED)[M][number];");
  lines.push("");
  lines.push("/** The Postgres role a module's transactions run as. */");
  lines.push("export function roleFor(module: ModuleName): string {");
  lines.push('  return `module_${module.replace(/-/g, "_")}`;');
  lines.push("}");
  lines.push("");

  return lines.join("\n");
}

/** Writes both artifacts, creating their directories if needed. */
function write(sql: string, ts: string): void {
  mkdirSync(dirname(SQL_PATH), { recursive: true });
  mkdirSync(dirname(TS_PATH), { recursive: true });
  writeFileSync(SQL_PATH, sql);
  writeFileSync(TS_PATH, ts);
}

/**
 * Compares the generated content with what is on disk.
 *
 * @returns The paths that are stale or missing, repo-relative. Empty when both
 *   files are current.
 */
function stale(sql: string, ts: string): string[] {
  const out: string[] = [];
  for (const [path, want, label] of [
    [SQL_PATH, sql, "db/grants.generated.sql"],
    [TS_PATH, ts, "packages/core/src/kernel/db.modules.generated.ts"],
  ] as const) {
    let have: string | undefined;
    try {
      have = readFileSync(path, "utf8");
    } catch {
      have = undefined;
    }
    // Compare without line endings: a Windows checkout with core.autocrlf holds
    // the generated files as CRLF, and the generator writes LF. Byte equality
    // reported both files stale on every Windows run while git saw no change.
    if (have?.replace(/\r\n/g, "\n") !== want) out.push(label);
  }
  return out;
}

function main(argv: string[]): number {
  const ownership = readOwnership();
  const sql = renderGrantsSql(ownership);
  const ts = renderModulesTs(ownership);

  if (argv.includes("--check")) {
    const out = stale(sql, ts);
    if (out.length === 0) {
      console.log("gen-grants: up to date");
      return 0;
    }
    for (const path of out) {
      console.error(`gen-grants: ${path} is stale. Run \`pnpm gen:grants\`.`);
    }
    return 1;
  }

  write(sql, ts);
  console.log(
    `gen-grants: wrote db/grants.generated.sql and packages/core/src/kernel/db.modules.generated.ts`,
  );
  console.log(`gen-grants: ${Object.keys(ownership.modules).length} modules`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  process.exit(main(process.argv.slice(2)));
}
